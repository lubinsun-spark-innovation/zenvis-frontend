import { createHash } from 'node:crypto';
import { mkdir, readFile, writeFile } from 'node:fs/promises';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

import {
  chartPalette,
  designTokens,
  elementTokens,
  naiveTokens,
  pluginClasses,
  uiContract,
} from '../src/theme/design-tokens.mjs';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const check = process.argv.includes('--check');
const stableJson = value => JSON.stringify(value, Object.keys(value).sort(), 2);
const tokenHash = createHash('sha256').update(stableJson(designTokens)).digest('hex').slice(0, 16);
const cssDeclarations = tokens =>
  Object.entries(tokens)
    .map(([name, value]) => `  ${name}: ${value};`)
    .join('\n');
const banner = marker => `/* GENERATED by scripts/generate-ui-contract.mjs. ${marker} */`;

const outputs = new Map();
outputs.set(
  'src/assets/styles/generated/design-tokens.scss',
  `${banner('Do not edit directly.')}\n:root {\n  color-scheme: light;\n  --zv-ui-contract: '${
    uiContract.contractVersion
  }';\n${cssDeclarations(designTokens)}\n}\n`,
);
outputs.set(
  'src/assets/styles/generated/element-tokens.scss',
  `${banner('Do not edit directly.')}\n:root {\n${cssDeclarations(elementTokens)}\n}\n`,
);
outputs.set(
  'public/amis/plugin-ui/v1/zenvis-plugin-tokens.css',
  `${banner(
    `contract ${uiContract.contractVersion}; token hash ${tokenHash}.`,
  )}\n:root {\n  color-scheme: light;\n  --zv-ui-contract: '${
    uiContract.contractVersion
  }';\n  --zv-token-hash: '${tokenHash}';\n${cssDeclarations(
    designTokens,
  )}\n}\n\nhtml[data-zenvis-ui='${uiContract.contractVersion}'] {\n  color-scheme: light;\n}\n`,
);
outputs.set(
  'src/theme/generated/naive-theme.ts',
  `// GENERATED by scripts/generate-ui-contract.mjs. Do not edit directly.\nimport type { GlobalThemeOverrides } from 'naive-ui';\n\nexport const generatedNaiveTheme: GlobalThemeOverrides = ${JSON.stringify(
    { common: naiveTokens },
    null,
    2,
  )};\n`,
);
outputs.set(
  'src/theme/generated/plugin-contract.ts',
  `// GENERATED by scripts/generate-ui-contract.mjs. Do not edit directly.\nexport type PluginUiProfile = 'standard' | 'immersive' | 'external';\n\nexport const ZENVIS_UI_CONTRACT_VERSION = '${
    uiContract.contractVersion
  }' as const;\nexport const ZENVIS_UI_RENDERER = '${
    uiContract.renderer
  }' as const;\nexport const ZENVIS_UI_TOKEN_HASH = '${tokenHash}' as const;\nexport const ZENVIS_UI_TOKENS = Object.freeze(${JSON.stringify(
    designTokens,
    null,
    2,
  )});\nexport const ZENVIS_PLUGIN_CLASSES = Object.freeze(${JSON.stringify(
    pluginClasses,
    null,
    2,
  )});\n`,
);
outputs.set(
  'public/amis/plugin-ui/v1/zenvis-plugin-chart-palette.js',
  `// GENERATED by scripts/generate-ui-contract.mjs. Do not edit directly.\n(function (global) {\n  'use strict';\n  global.ZenVisPluginChartPalette = Object.freeze(${JSON.stringify(
    chartPalette,
    null,
    2,
  )});\n})(window);\n`,
);

let failed = false;
for (const [relativePath, content] of outputs) {
  const target = resolve(root, relativePath);
  if (check) {
    const current = await readFile(target, 'utf8').catch(() => '');
    if (current !== content) {
      console.error(`out of date: ${relativePath}`);
      failed = true;
    }
  } else {
    await mkdir(dirname(target), { recursive: true });
    await writeFile(target, content);
    console.log(`generated: ${relativePath}`);
  }
}

if (failed) process.exitCode = 1;
